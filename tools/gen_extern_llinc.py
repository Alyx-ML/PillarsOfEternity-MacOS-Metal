#!/usr/bin/env python3
"""Generate extern.llinc for one translated module.

SRW writes "include extern.llinc" before its own import declarations. This
file connects each import to its runtime thunk:

  define NAME NAME_asm2c      for every import of the module. llasm then
                              uses the thunk wherever the module uses the
                              import (calls and import address table data).
  proc NAME_asm2c external    for imports that only data references.
                              SRW declares an import only when code calls it
                              ("proc NAME external"); the define changes
                              that declaration to the thunk name.

Every import must have an entry in runtime/imports.spec. A missing entry is
an error, so the build stops before a missing import can be linked.

With --missing=<file>, a missing entry is not an error: the script writes
the encoded name of each missing import to <file> (one name for each line,
sorted) and declares the import with its thunk name <name>_asm2c, as for an
import with an entry. The runtime has no thunk with that name, so the link
of a host with the module stops with an undefined symbol for each missing
import until runtime/imports.spec and the runtime implement it. Use this
option to translate a module before its imports are implemented.

Usage: gen_extern_llinc.py [--missing=<file>] <imports.spec> <main.llasm> <output extern.llinc> [<data.llinc>...]
  Address-preserving output has no data segments: give no data files.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from importspec import read_spec  # noqa: E402

DECL_RE = re.compile(r'^proc\s+(\S+)\s+external\b')
DADDR_RE = re.compile(r'^daddr\s+(\S+)\s*$')


def main() -> int:
    args = sys.argv[1:]
    missing_file = None
    if args and args[0].startswith('--missing='):
        missing_file = args[0][len('--missing='):]
        args = args[1:]
        if not missing_file:
            sys.stderr.write('error: --missing needs a file name\n')
            return 2
    if len(args) < 3:
        sys.stderr.write(__doc__)
        return 2
    spec_file, main_file, out_file, data_files = args[0], args[1], args[2], args[3:]
    spec = read_spec(spec_file)
    declared = set()
    with open(main_file, encoding='latin-1') as f:
        for line in f:
            m = DECL_RE.match(line)
            if m:
                declared.add(m.group(1))
    referenced = set()
    for path in data_files:
        with open(path, encoding='latin-1') as f:
            for line in f:
                m = DADDR_RE.match(line)
                if m and not m.group(1).startswith('loc_'):
                    referenced.add(m.group(1))
    imports = declared | referenced
    missing = sorted(n for n in imports if n not in spec)
    if missing and missing_file is None:
        for n in missing:
            sys.stderr.write(f'error: import {n} has no entry in {spec_file}\n')
        return 1
    if missing_file is not None:
        with open(missing_file, 'w', encoding='latin-1') as f:
            f.writelines(n + '\n' for n in missing)

    def thunk(n):
        # An import name from SRW is already encoded (see importspec.py).
        return spec[n].thunk if n in spec else n + '_asm2c'
    with open(out_file, 'w', encoding='latin-1') as f:
        f.write(';; Generated by tools/gen_extern_llinc.py, do not edit.\n')
        f.write(';; Connects the imports of this module to the runtime thunks.\n\n')
        for n in sorted(imports):
            f.write(f'define {n} {thunk(n)}\n')
        f.write('\n')
        for n in sorted(referenced - declared):
            f.write(f'proc {thunk(n)} external\n')
    print(f'{len(imports)} imports, {len(referenced - declared)} referenced only from data'
          + (f', {len(missing)} without an entry in {spec_file} (listed in {missing_file})' if missing_file is not None else ''))
    return 0


if __name__ == '__main__':
    sys.exit(main())
